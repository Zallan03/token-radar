// Token launch radar, model radar-2: one snapshot in, one ranked board out.
//
// The board ranks every pre-token protocol the snapshot can rank: the whole
// watchlist (the floor, never the ceiling) plus every other pre-token protocol
// that is not a wrapped, staked or bridged product of a token that already
// trades. A protocol "records no token" when the snapshot carries no market
// cap, no CoinGecko id and no symbol for it; that is DefiLlama's record, not
// proof it has none, so the board never claims a protocol has no token.
//
// Implied value is derived from the snapshot's own figures only, in four
// factors, none of them a hardcoded list of names:
//
//   category multiple: the median market-cap-to-TVL ratio of the snapshot's
//     OWN live-token protocols in the same category (at least 3 of them,
//     else the global median), clamped to [0.05, 1.5]. The snapshot's live
//     market is the yardstick: a lending protocol's token is priced like
//     lending tokens actually trade, a DEX's like DEX tokens trade.
//   growth:  1 + clamp(change_7d, -50, 100) / 100 * 0.6
//   maturity: 0.7 + 0.3 * min(age_days, 1460) / 1460 (unknown age: 365 days)
//   breadth: 1 + 0.02 * min(chains - 1, 5)
//
//   implied_value_usd = round(tvl_usd * category * growth * maturity * breadth)
//
// Farm plans are built from the same record (category, chains, TVL tier,
// age): each step names a concrete action, what it costs and how long it
// takes. No protocol name is ever special-cased anywhere in this file.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

